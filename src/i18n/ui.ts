import type { Locale } from '../types';
import type { LocalizedText } from '../services/contracts/common';

export interface Copy {
  en: string;
  ar: string;
}

export const tx = (value: Copy, locale: Locale): string => (locale === 'ar' ? value.ar : value.en);

export const text = (value: LocalizedText | undefined, locale: Locale, fallback = ''): string => {
  if (value === undefined || value === null) return fallback;
  if (typeof value === 'string') return value || fallback;
  return (locale === 'ar' ? value.ar : value.en) ?? value.en ?? fallback;
};

